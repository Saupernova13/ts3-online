def va(p):
    return f"0x{IMAGE_BASE + int(p['rva'], 16):x}"


def change(p):
    if p["kind"] == "bytes":
        return f"`{p['orig']}` -> `{p['new']}`"
    if p["kind"] == "rip_reloc":
        return f"disp at +{p['disp_pos']} -> buffer +{p['target_off']}"
    if p["kind"] == "hook":
        pre = f" (prefix `{p['prefix']}`)" if p.get("prefix") else ""
        steal = f", steals {p['steal']}" if p.get("steal") else ""
        return f"{p['mode']} -> `{p['hook']}`{pre}, {len(p['orig']) // 2} bytes{steal}"
    return p["kind"]


def cell(s):
    return s.replace("|", "\\|")


def render(doc):
    patches = doc["patches"]
    optional = set(doc.get("optional_groups", []))
    order = [g for g in GROUPS if any(p["group"] == g for p in patches)]
    order += sorted({p["group"] for p in patches} - set(order))
    r = doc["relocate"]
    out = [
        "# Patch catalogue",
        "",
        "<!-- Generated by tools/patch_catalog.py from loader/patches.json; do not edit by hand. -->",
        "",
        "Every change the loader (`dinput8.dll`) makes to the running game. Nothing is written to the exe",
        "on disk. Addresses are VAs of the analysed exe (image base `0x140000000`, TimeDateStamp",
        f"`{doc['game']['time_date_stamp']}`); the loader rebases them and checks every original byte",
        "before writing anything. If one differs, nothing is applied.",
        "",
        f"Relocation: `{r['old_size']}` bytes at RVA `{r['old_rva']}` -> a `{r['new_size']}` buffer; fields "
        f"from `+{r['tail_start']}` move by `+{r['tail_shift']}`.",
        "",
        "| group | patches | what it does | source | status |",
        "|---|---|---|---|---|",
    ]
    for g in order:
        n = sum(1 for p in patches if p["group"] == g)
        what, src, status = GROUPS.get(g, ("", "", ""))
        name = f"{g} (optional)" if g in optional else g
        out.append(f"| {name} | {n} | {cell(what)} | {cell(src)} | {cell(status)} |")
    out += ["", f"Total: {len(patches)} patches.", ""]
    for g in order:
        out += [f"## {g}", "", "| VA | change | note |", "|---|---|---|"]
        for p in sorted((p for p in patches if p["group"] == g), key=lambda p: int(p["rva"], 16)):
            out.append(f"| `{va(p)}` | {cell(change(p))} | {cell(p.get('note', ''))} |")
        out.append("")
    return "\n".join(out)


def write(doc_path="loader/patches.json", out_path="docs/PATCHES.md"):
    doc = json.load(open(doc_path, encoding="utf-8"))
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(doc))
    return out_path


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--doc", default="loader/patches.json")
    ap.add_argument("--out", default="docs/PATCHES.md")
    a = ap.parse_args()
    print(write(a.doc, a.out))
